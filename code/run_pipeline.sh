#!/usr/bin/env bash

################################################################################
# MASTER PIPELINE LAUNCHER
#
# Runs code/run_pipeline.R from the GitHub project root.
#
# The active data environment is controlled inside:
#
#   code/run_pipeline.R
#
# using:
#
#   PIPELINE_MODE <- "UAMS"
#
# or:
#
#   PIPELINE_MODE <- "EXAMPLE"
#
################################################################################


################################################################################
# 1. STOP ON ERRORS
################################################################################

set -euo pipefail


################################################################################
# 2. LOCATE PROJECT ROOT
################################################################################

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"


################################################################################
# 3. MOVE TO PROJECT ROOT
################################################################################

cd "$PROJECT_ROOT"


################################################################################
# 4. REPORT PROJECT LOCATION
################################################################################

echo
echo "============================================================"
echo "STARTING MYELOMA 1q / PolyIG PIPELINE"
echo "============================================================"
echo "Project root:"
echo "  $PROJECT_ROOT"
echo
echo "Pipeline mode will be read from:"
echo "  code/run_pipeline.R"
echo "============================================================"
echo


################################################################################
# 5. RUN MASTER R PIPELINE
################################################################################

exec Rscript "$SCRIPT_DIR/run_pipeline.R"
